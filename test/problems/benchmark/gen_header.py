def read_scs_data_file(path):
    """The cone and data of an SCS data file (format of SCS 3.3, src/rw.c).

    The settings and the extension section after the data are not read."""
    buf = Path(path).read_bytes()
    pos = 0

    def take(fmt, count):
        nonlocal pos
        size = struct.calcsize("<" + fmt) * count
        vals = struct.unpack_from("<%d%s" % (count, fmt), buf, pos)
        pos += size
        return list(vals)

    int_size, float_size, ver_len = take("I", 3)
    pos += ver_len  # the version string
    if float_size != 8:
        sys.exit("%s: floats are %d bytes, expected 8" % (path, float_size))
    ifmt = {4: "i", 8: "q"}[int_size]

    def ints(count):
        return take(ifmt, count)

    def one():
        return ints(1)[0]

    def floats(count):
        return take("d", count)

    cone = {"z": one(), "l": one()}
    bsize = one()
    cone["bsize"] = bsize
    cone["bl"] = floats(max(bsize - 1, 0))
    cone["bu"] = floats(max(bsize - 1, 0))
    cone["q"] = ints(one())
    cone["s"] = ints(one())
    cone["ep"] = one()
    cone["ed"] = one()
    cone["p"] = floats(one())
    m = one()
    n = one()
    b = floats(m)
    c = floats(n)

    def matrix():
        rows, cols = one(), one()
        p = ints(cols + 1)
        x = floats(p[-1])
        i = ints(p[-1])
        return {"m": rows, "n": cols, "x": x, "i": i, "p": p}

    a = matrix()
    p = matrix() if one() else None
    return {"m": m, "n": n, "b": b, "c": c, "A": a, "P": p, "cone": cone}


def literal(v):
    """Shortest decimal that rounds back to v ("3." for 3.0, "-0." for -0.0)."""
    if math.isinf(v):
        return "INFINITY" if v > 0 else "-INFINITY"
    if math.isnan(v):
        sys.exit("NaN in the data")
    s = repr(float(v))
    if s.endswith(".0"):
        s = s[:-1]
    return s


def array(ctype, name, vals, fmt):
    """A file-scope static array, its values wrapped at 80 columns."""
    lines, line = [], "   "
    for v in vals:
        item = " " + fmt(v) + ","
        if len(line) + len(item) > 80:
            lines.append(line)
            line = "   "
        line += item
    lines.append(line)
    return ["static %s %s[] = {" % (ctype, name)] + lines + ["};"]


def describe_cones(cone):
    parts = []
    if cone["z"]:
        parts.append("zero cone %d" % cone["z"])
    if cone["l"]:
        parts.append("nonnegative cone %d" % cone["l"])
    if cone["bsize"]:
        parts.append("box cone %d (t and %d bounded rows)"
                     % (cone["bsize"], cone["bsize"] - 1))
    if cone["q"]:
        parts.append("second-order cones %s" % cone["q"])
    if cone["s"]:
        sizes = {}
        for s in cone["s"]:
            sizes[s] = sizes.get(s, 0) + 1
        parts.append("PSD " + ", ".join(
            "%d x %d%s" % (s, s, "" if c == 1 else " (x %d)" % c)
            for s, c in sizes.items()))
    return "; ".join(parts)


def header(name, meta, data, scs_sha256):
    cid = "bench_" + name.lower()
    a, p, cone = data["A"], data["P"], data["cone"]
    if cone["ep"] or cone["ed"] or cone["p"]:
        sys.exit("%s: exponential and power cones are not handled" % name)
    has_p = p is not None and p["p"][-1] > 0
    sizes = "m = %d, n = %d, nnz(A) = %d" % (data["m"], data["n"], a["p"][-1])
    if p is not None:
        sizes += ", nnz(P, upper triangle) = %d" % p["p"][-1]
    out = ["/*"]
    body = list(meta["title"]) + [""] + list(meta["source"])
    body += list(HARNESS)
    body += ["  " + meta["file"], "  (SHA-256 %s)" % meta["file_sha256"]]
    body += list(meta["file_note"]) + [""]
    body += list(KNOWN[name]) + [""]
    body += list(meta["posing"])
    body += [
        "  The arrays below are the data the adapter hands SCS, bit for bit,",
        "  generated by gen_header.py in this directory from the SCS data file",
        "  that SCS writes for it (SHA-256",
        "  %s)." % scs_sha256,
        "  " + sizes + ";",
        "  " + describe_cones(cone) + ".",
    ]
    if p is not None and not has_p:
        body += [
            "  The file's P has no entries; it is passed here as P = NULL, which",
            "  SCS solves the same, bit for bit.",
        ]
    body += [""] + list(meta["licence"])
    out += [(" * " + line).rstrip() for line in body]
    out += [" */", ""]
    guard = "SCS_BENCH_%s_H_GUARD" % name.upper()
    out += ["#ifndef " + guard, "#define " + guard, ""]
    out += ['#include "glbopts.h"', '#include "scs.h"', "", "#include <math.h>",
            "#include <string.h>", ""]
    out += array("scs_float", cid + "_b", data["b"], literal)
    out += array("scs_float", cid + "_c", data["c"], literal)
    out += array("scs_float", cid + "_A_x", a["x"], literal)
    out += array("scs_int", cid + "_A_i", a["i"], str)
    out += array("scs_int", cid + "_A_p", a["p"], str)
    if has_p:
        out += array("scs_float", cid + "_P_x", p["x"], literal)
        out += array("scs_int", cid + "_P_i", p["i"], str)
        out += array("scs_int", cid + "_P_p", p["p"], str)
    if cone["bsize"] > 1:
        out += array("scs_float", cid + "_bl", cone["bl"], literal)
        out += array("scs_float", cid + "_bu", cone["bu"], literal)
    if cone["q"]:
        out += array("scs_int", cid + "_q", cone["q"], str)
    if cone["s"]:
        out += array("scs_int", cid + "_s", cone["s"], str)
    out += [
        "",
        "/* Point d and k at the data above, which stays where it is (SCS",
        " * copies what it uses). */",
        "static void %s_set(ScsData *d, ScsCone *k) {" % cid,
        "  static ScsMatrix A;",
    ]
    if has_p:
        out.append("  static ScsMatrix P;")
    out += [
        "  memset(d, 0, sizeof(*d));",
        "  memset(k, 0, sizeof(*k));",
        "  A.m = %d;" % a["m"],
        "  A.n = %d;" % a["n"],
        "  A.x = %s_A_x;" % cid,
        "  A.i = %s_A_i;" % cid,
        "  A.p = %s_A_p;" % cid,
    ]
    if has_p:
        out += [
            "  P.m = %d;" % p["m"],
            "  P.n = %d;" % p["n"],
            "  P.x = %s_P_x;" % cid,
            "  P.i = %s_P_i;" % cid,
            "  P.p = %s_P_p;" % cid,
        ]
    out += [
        "  d->m = %d;" % data["m"],
        "  d->n = %d;" % data["n"],
        "  d->A = &A;",
        "  d->P = %s;" % ("&P" if has_p else "SCS_NULL"),
        "  d->b = %s_b;" % cid,
        "  d->c = %s_c;" % cid,
    ]
    if cone["z"]:
        out.append("  k->z = %d;" % cone["z"])
    if cone["l"]:
        out.append("  k->l = %d;" % cone["l"])
    if cone["bsize"]:
        out.append("  k->bsize = %d;" % cone["bsize"])
    if cone["bsize"] > 1:
        out += ["  k->bl = %s_bl;" % cid, "  k->bu = %s_bu;" % cid]
    if cone["q"]:
        out += ["  k->qsize = %d;" % len(cone["q"]), "  k->q = %s_q;" % cid]
    if cone["s"]:
        out += ["  k->ssize = %d;" % len(cone["s"]), "  k->s = %s_s;" % cid]
    out += ["}", "", "#endif", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("files", nargs="+", help="SCS data files, NAME.scs")
    ap.add_argument("--out-dir", default=str(Path(__file__).resolve().parent),
                    help="where to write NAME.h (default: this directory)")
    args = ap.parse_args()
    for f in args.files:
        name = Path(f).name
        if name.endswith(".scs"):
            name = name[:-4]
        if name not in PROBLEMS:
            sys.exit("%s: not in the table (%s)" % (name, ", ".join(PROBLEMS)))
        meta = PROBLEMS[name]
        digest = hashlib.sha256(Path(f).read_bytes()).hexdigest()
        if digest != meta["scs_sha256"]:
            sys.exit("%s: SHA-256 %s, the table has %s"
                     % (f, digest, meta["scs_sha256"]))
        text = header(name, meta, read_scs_data_file(f), digest)
        out = Path(args.out_dir) / (name.lower() + ".h")
        out.write_text(text)
        print("%s: %d bytes" % (out, len(text)))


if __name__ == "__main__":
    main()
